export class MapStorage {
  private static STORAGE_KEY = 'sanguine_current_castle_map';

  public static loadMap(): PlayerCastleMap {
    try {
      const data = localStorage.getItem(this.STORAGE_KEY);
      if (data) {
        return JSON.parse(data);
      }
    } catch {
      // Fallback
    }
    return JSON.parse(JSON.stringify(DEFAULT_CASTLE_MAP));
  }

  public static saveMap(map: PlayerCastleMap) {
    try {
      localStorage.setItem(this.STORAGE_KEY, JSON.stringify(map));
    } catch {
      // Ignore
    }
  }

  public static resetToDefault(): PlayerCastleMap {
    const fresh = JSON.parse(JSON.stringify(DEFAULT_CASTLE_MAP));
    this.saveMap(fresh);
    return fresh;
  }
}
